"""Quantize the same BF16 GGUF using no imatrix and chat/math/code imatrices.

Also optionally runs a mixed-precision plan generated by imatrix_research.py.
Outputs: GGUF files, logs, a CSV run manifest, and a Markdown report.
No JSON files are written by this script.
"""
import argparse
import csv
import os
import shutil
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path


def find_root():
    for parent in (Path.cwd(), *Path.cwd().parents, *Path(__file__).resolve().parents):
        if (parent / 'models' / 'Llama-3.2-1B-Instruct-BF16.gguf').is_file():
            return parent
    raise FileNotFoundError('Could not locate repository with models/Llama-3.2-1B-Instruct-BF16.gguf; use --root /path/to/repo')


def resolve_executable(option):
    paths = [Path(option).expanduser()] if option else []
    paths += [Path.home() / 'llama.cpp/build-cpu/bin/llama-quantize',
              Path.home() / 'llama.cpp/build/bin/llama-quantize']
    found = shutil.which('llama-quantize')
    if found:
        paths.append(Path(found))
    for p in paths:
        if p.is_file() and os.access(p, os.X_OK):
            return p.resolve()
    raise FileNotFoundError('llama-quantize not found. Build it: cd ~/llama.cpp && cmake --build build-cpu --target llama-quantize -j 4')


def write_manifest(path, records):
    fields = ['run', 'calibration', 'precision', 'imatrix', 'model', 'size_mib', 'status', 'log']
    with path.open('w', newline='', encoding='utf-8') as f:
        writer = csv.DictWriter(f, fieldnames=fields)
        writer.writeheader()
        writer.writerows(records)


def write_report(path, records, source, quantizer):
    lines = ['# imatrix Quantization Experiments', '',
             f'Source checkpoint: `{source}`',
             f'Quantizer: `{quantizer}`',
             f'Generated: {datetime.now(timezone.utc).isoformat(timespec="seconds")}', '',
             '| Variant | Status | Size (MiB) | Imatrix |',
             '|---|---|---:|---|']
    for r in records:
        lines.append(f"| {r['run']} | {r['status']} | {r['size_mib'] or '—'} | {r['calibration']} |")
    lines += ['', 'These are **file size** measurements, not model accuracy or inference memory.',
              'For performance conclusions, evaluate every produced GGUF using the same GSM8K, IFEval, MMLU settings.',
              'Mixed precision depends on a separately generated tensor_types.txt recommendation and should be validated.', '']
    path.write_text('\n'.join(lines), encoding='utf-8')


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--root', type=Path, help='Repository root; autodetected by BF16 checkpoint if omitted')
    p.add_argument('--quantizer', help='Path to llama-quantize executable')
    p.add_argument('--include-mixed', action='store_true', help='Also quantize with existing results/imatrix_analysis/tensor_types.txt')
    p.add_argument('--dry-run', action='store_true', help='Show commands without executing')
    p.add_argument('--force', action='store_true', help='Re-quantize even if output exists')
    a = p.parse_args()

    root = a.root.expanduser().resolve() if a.root else find_root()
    source = root / 'models/Llama-3.2-1B-Instruct-BF16.gguf'
    if not source.is_file():
        p.error(f'Missing BF16 source: {source}')
    quantizer = resolve_executable(a.quantizer)
    imatrix_dir = root / 'models/imatrix'
    model_dir = root / 'models/imatrix_quants'
    result_dir = root / 'results/imatrix_quantization'
    if not a.dry_run:
        model_dir.mkdir(parents=True, exist_ok=True)
        result_dir.mkdir(parents=True, exist_ok=True)

    variants = [('uniform_q4', 'none', None, 'Q4_K_M', None)]
    for domain in ('chat', 'math', 'code'):
        imatrix = imatrix_dir / f'{domain}.imatrix.gguf'
        if not imatrix.is_file():
            p.error(f'Missing input: {imatrix}')
        variants.append((f'{domain}_q4_imatrix', domain, imatrix, 'Q4_K_M', None))
    if a.include_mixed:
        type_file = root / 'results/imatrix_analysis/tensor_types.txt'
        if not type_file.is_file() or not type_file.read_text().strip():
            p.error(f'Mixed plan missing/empty: {type_file}. Run imatrix_research.py recommend first.')
        variants.append(('chat_mixed_q4_q6', 'chat', imatrix_dir / 'chat.imatrix.gguf', 'Q4_K_M', type_file))

    records = []
    for name, domain, imatrix, quant_type, type_file in variants:
        destination = model_dir / f'Llama-3.2-1B-Instruct-{name}.gguf'
        log_file = result_dir / f'{name}.log'
        command = [str(quantizer)]
        if imatrix:
            command += ['--imatrix', str(imatrix)]
        if type_file:
            command += ['--tensor-type-file', str(type_file)]
        command += [str(source), str(destination), quant_type]
        print('\n' + name + ': ' + ' '.join(command), flush=True)
        if a.dry_run:
            continue
        record = dict(run=name, calibration=domain, precision=quant_type,
                      imatrix=str(imatrix.relative_to(root)) if imatrix else '',
                      model=str(destination.relative_to(root)), size_mib='',
                      status='pending', log=str(log_file.relative_to(root)))
        if destination.is_file() and destination.stat().st_size > 0 and not a.force:
            record['status'] = 'skipped_existing'
            record['size_mib'] = f'{destination.stat().st_size / 1024**2:.2f}'
        else:
            # Log stdout/stderr to disk without swallowing errors.
            with log_file.open('w', encoding='utf-8') as log:
                log.write('COMMAND: ' + ' '.join(command) + '\n\n')
                log.flush()
                proc = subprocess.run(command, stdout=log, stderr=subprocess.STDOUT)
            if proc.returncode != 0 or not destination.is_file() or destination.stat().st_size == 0:
                record['status'] = f'failed_exit_{proc.returncode}'
                records.append(record)
                write_manifest(result_dir / 'quantization_runs.csv', records)
                write_report(result_dir / 'REPORT.md', records, source, quantizer)
                raise RuntimeError(f'{name} failed. See {log_file}')
            record['status'] = 'completed'
            record['size_mib'] = f'{destination.stat().st_size / 1024**2:.2f}'
        print(f"{name}: {record['status']} ({record['size_mib']} MiB)", flush=True)
        records.append(record)
        write_manifest(result_dir / 'quantization_runs.csv', records)
        write_report(result_dir / 'REPORT.md', records, source, quantizer)
    if a.dry_run:
        print('\nDry run complete; no files generated.')
    else:
        print(f'\nResults: {result_dir / "quantization_runs.csv"}')
        print(f'Models: {model_dir}')


if __name__ == '__main__':
    main()
